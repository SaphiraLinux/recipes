#!/bin/sh

pkgname=qemu-user
pkgver=11.1.1
pkgrel=1
pkgarch=${SAPHIRA_ARCH:-x86_64}
pkgdesc='QEMU Linux-user emulators (dynamic, all supported guest architectures)'
license='GPL-2.0-or-later'
origin=qemu-user
repo=saphira
url=https://www.qemu.org/
source=https://download.qemu.org/qemu-11.1.1.tar.xz
sha256=079ffbff8a7111bbc89022107cbabf3bbfd614d5fc9d7cc675991196aca12482

# Linux-user only: needs glib at runtime. No display (VNC/SPICE),
# no block backends, no FDT (system-machine data, not user mode).
depends="glib"
# pcre2-dev/libffi-dev: glib-2.0.pc Requires libpcre2-8 and
# gobject-2.0.pc Requires libffi; the meson probes fail without them
# in the sysroot (qemu r6 build failure precedent).
makedepends="
	binutils
	bison
	flex
	gawk
	gcc
	glib-dev
	libffi-dev
	pcre2-dev
	saphira-linux-uapi-headers
	make
	meson
	ninja
	pkgconf
	python3
	python3-pip
	setuptools
	wheel
	zlib-dev
"

# Dynamic linux-user emulators for foreign-architecture chroots and
# binfmt_misc. System emulation, tools (qemu-img etc) and the guest
# agent live in their own packages; this staging must not contain
# them (asserted in recipe_install). binfmt_misc fragments are
# opt-in only: inert files under /usr/lib/binfmt.d, no post-install
# hook, never auto-enabled. systemd users enable
# systemd-binfmt.service; OpenRC users register manually (see README).
recipe_build()
{
	cd "$SRC"
	./configure --prefix=/usr \
		--sysconfdir=/etc \
		--localstatedir=/var \
		--disable-download \
		--disable-system --enable-linux-user --disable-bsd-user \
		--disable-tools --disable-guest-agent \
		--disable-kvm --enable-tcg \
		-Dfdt=disabled \
		--disable-gtk --disable-sdl --disable-opengl \
		--disable-vnc --disable-spice --disable-usb-redir \
		--disable-tpm \
		--disable-docs --disable-werror \
		--disable-libssh
	make -j${JOBS:-$(nproc)}
}

recipe_install()
{
	make DESTDIR="$PKGDEST" install
	# Ownership: /usr/share/qemu/* (pc-bios firmware, option ROMs) is
	# owned exclusively by qemu (main). linux-user emulators never use
	# it, but upstream `make install` copies it for every configuration.
	# Strip it unconditionally so a future upstream install addition
	# cannot silently reintroduce a one-owner violation.
	rm -rf "$PKGDEST/usr/share/qemu"
	[ ! -e "$PKGDEST/usr/share/qemu" ] || { echo "ERROR: qemu-user must not ship /usr/share/qemu (qemu owns the firmware)" >&2; return 1; }
	# Headers belong to qemu (main): the plugin API header installs with
	# every configuration. linux-user needs none of it.
	rm -rf "$PKGDEST/usr/include"
	[ ! -e "$PKGDEST/usr/include" ] || { echo "ERROR: qemu-user must not ship /usr/include (qemu owns the headers)" >&2; return 1; }
	# Ownership: no system emulators, no tools, no guest agent.
	[ ! -e "$PKGDEST/usr/bin/qemu-ga" ] || { echo "ERROR: qemu-user must not ship qemu-ga" >&2; return 1; }
	[ ! -e "$PKGDEST/usr/bin/qemu-img" ] || { echo "ERROR: qemu-user must not ship qemu-img (qemu owns tools)" >&2; return 1; }
	ls "$PKGDEST"/usr/bin/qemu-system-* >/dev/null 2>&1 && { echo "ERROR: qemu-user must not ship qemu-system-*" >&2; return 1; } || true
	# Proof: at least one dynamic linux-user emulator is staged.
	ls "$PKGDEST"/usr/bin/qemu-* >/dev/null 2>&1 || { echo "ERROR: qemu-user staging has no qemu-* emulators" >&2; return 1; }
	# binfmt_misc integration (opt-in, never auto-enabled): generate
	# systemd-binfmt fragments from the upstream script (genuine ELF
	# magic, not invented) pointing at the dynamic interpreters.
	# Inert files under /usr/lib/binfmt.d, no post-install hook.
	if [ -x "$SRC/scripts/qemu-binfmt-conf.sh" ]; then
		mkdir -p "$PKGDEST/usr/lib/binfmt.d" "$PKGDEST/usr/share/doc/qemu-user/binfmt"
		"$SRC/scripts/qemu-binfmt-conf.sh" \
			--systemd ALL --qemu-path /usr/bin \
			--exportdir "$PKGDEST/usr/lib/binfmt.d" >/dev/null 2>&1 || true
		cat > "$PKGDEST/usr/share/doc/qemu-user/binfmt/README" <<'EOF'
qemu-user binfmt_misc (opt-in, disabled by default)
---------------------------------------------------
Fragments in /usr/lib/binfmt.d/ register foreign-architecture ELF
interpreters. Installing this package does NOT activate them.
systemd: systemctl enable --now systemd-binfmt.service
OpenRC:  register manually, e.g.
  cat /usr/lib/binfmt.d/qemu-aarch64.conf \
    > /proc/sys/fs/binfmt_misc/register
(generated by upstream scripts/qemu-binfmt-conf.sh, never hand-invented.)
Do not enable dynamic and static families at once: use either the
qemu-user (dynamic) or the qemu-user-static fragments, not both.
EOF
	fi
}
