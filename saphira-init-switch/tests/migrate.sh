#!/bin/sh
# Hermetic tests for saphira-net-migrate. No live network, no root-owned
# paths: every case gets fixture dirs, a fake `ip`/`ovs-vsctl` on PATH,
# a fake sysfs, and env overrides. Fixtures mirror real machines:
# Hatched (MAC-match unit), production saphiraD (Name= unit with five
# IPv6 addresses + MTU), Egg (.conf shape).
#
# usage: migrate.sh PATH-TO-saphira-net-migrate

set -eu

[ "$#" -eq 1 ] || {
	printf 'usage: %s MIGRATE-SCRIPT\n' "$0" >&2
	exit 1
}
MIG=$1

test_tmp_base=${SAPHIRA_TMPDIR:-/build/test-tmp}
mkdir -p "$test_tmp_base"
T=$(mktemp -d "$test_tmp_base/saphira-net-migrate-test.XXXXXX")
trap 'rm -rf "$T"' EXIT HUP INT TERM

PASS=0
fail()
{
	printf 'FAIL: %s\n' "$1" >&2
	exit 1
}
pass()
{
	PASS=$((PASS + 1))
	printf 'ok: %s\n' "$1"
}

# --- fake bin -------------------------------------------------------------
mkdir -p "$T/fakebin"
cat >"$T/fakebin/ip" <<'EOF'
#!/bin/sh
# Serves $FAKE_IP_TABLE for `ip -o link show`; anything else fails.
if [ "${1:-} ${2:-}" = "-o link" ]; then
	cat "$FAKE_IP_TABLE"
else
	exit 1
fi
EOF
cat >"$T/fakebin/ovs-vsctl" <<'EOF'
#!/bin/sh
# Exit 0 iff a known device from $FAKE_OVS_DEVICES appears in argv.
for a in "$@"; do
	for d in $FAKE_OVS_DEVICES; do
		[ "$a" = "$d" ] && exit 0
	done
done
exit 1
EOF
chmod 755 "$T/fakebin/ip" "$T/fakebin/ovs-vsctl"

# --- case setup helper ----------------------------------------------------
newcase()
{
	C=$T/$1
	mkdir -p "$C/sys" "$C/net" "$C/conf" "$C/sys/class/net"
	export SAPHIRA_NETMIGRATE_SYSTEMD_DIR=$C/sys
	export SAPHIRA_NETMIGRATE_CONF_DIR=$C/conf
	export SAPHIRA_NETMIGRATE_SYSFS=$C/sysfs
	export SAPHIRA_NETMIGRATE_TS=fixed-ts
	export FAKE_IP_TABLE=$C/iptable
	export FAKE_OVS_DEVICES=${FAKE_OVS_DEVICES:-}
	mkdir -p "$SAPHIRA_NETMIGRATE_SYSFS"
	PATH=$T/fakebin:/usr/bin:/bin
	export PATH
}

mkphys()
{
	# $1 = interface name present in the fake table and physical.
	mkdir -p "$SAPHIRA_NETMIGRATE_SYSFS/$1"
	touch "$SAPHIRA_NETMIGRATE_SYSFS/$1/device"
}

run_migrate()
{
	# Runs the tool, captures output, preserves exit code in RC.
	RC=0
	OUT=$("$MIG" "$@" 2>&1) || RC=$?
}

