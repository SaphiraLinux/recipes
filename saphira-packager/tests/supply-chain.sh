#!/bin/sh

# Vendored source supply chain: every archive a recipe CONSUMES must carry
# a sha256 sidecar, and its bytes must match the hash the recipe declares.
# No build and no network required.
#
# Policy encoded (see AGENTS.md / RECIPE_RULES.md "Source contract"):
# upstream archives are vendored as files/<basename> with a
# files/<basename>.sha256 sidecar holding "<sha>  <basename>", compatible
# with sha256sum -c.
#
# THE DISTINCTION THIS SUITE EXISTS TO GET RIGHT, and which a naive check
# gets backwards:
#
#   a CONSUMED archive must be pinned. It is build input, and its bytes are
#   what get compiled.
#
#   an UNREFERENCED archive in files/ is not build input at all. A tree can
#   legitimately carry a superseded tarball next to the current one -- and
#   17 of these did. Hashing those, or worse reporting them as tampering,
#   would be wrong in both directions: it manufactures a supply-chain
#   signal that does not exist, and it hides the real issue, which is tree
#   bloat. So they are REPORTED as orphans, never failed, and never
#   sidecarred: pinning a dead file is pinning nothing.
#
# A first pass of this analysis reported 17 "mismatches" between vendored
# bytes and declared hashes. Every one turned out to be a superseded
# archive the recipe no longer references (dnsmasq builds 2.93 while the
# tree also held 2.91, expat builds 2.8.2 while 2.7.1 lingered, and so on).
# The lesson is recorded here because it is the same lesson as the
# headless validator's "ibus inside libusb": a check that cannot tell an
# input from a leftover is worse than no check.
#
# usage: supply-chain.sh (operates on the source tree it lives in)

set -eu

root=$(CDPATH= cd -- "$(dirname -- "$0")/../.." && pwd)

fail()
{
	printf '%s\n' "supply-chain: $*" >&2
	exit 1
}

checks=0
ok()
{
	checks=$((checks + 1))
	printf '  ok   %s\n' "$1"
}

scratch=${SAPHIRA_TMPDIR:-/build/tmp}
mkdir -p "$scratch" || fail "cannot create scratch under $scratch"
work=$(mktemp -d "$scratch/supply-chain.XXXXXX")
trap 'rm -rf -- "$work"' EXIT HUP INT TERM

# Enumerate the vendored archives: files/<pkg>/files/<archive>.
find "$root" -path "$root/.git" -prune -o -type f \
	\( -name '*.tar.gz' -o -name '*.tar.xz' -o -name '*.tar.bz2' \
	-o -name '*.tar.zst' -o -name '*.tar.lz' -o -name '*.tar.lzma' \
	-o -name '*.tgz' -o -name '*.tbz2' -o -name '*.zip' -o -name '*.whl' \) \
	-print | sort > "$work/archives"
[ -s "$work/archives" ] || fail "no vendored archives found under $root"

# The recipe list is needed for the cross-recipe reference check below.
find "$root" -path "$root/.git" -prune -o -type f -name recipe.sh -print |
	sort > "$work/recipes"
[ -s "$work/recipes" ] || fail "no recipes found under $root"

# --- 1. every CONSUMED archive is pinned, and its bytes verify --------

consumed=0
pinned=0
unpinned=""
mismatch=""
: > "$work/report"

while IFS= read -r archive; do
	rel=${archive#"$root"/}
	pkg=$(printf '%s' "$rel" | cut -d/ -f1)
	base=${archive##*/}
	recipe=$root/$pkg/recipe.sh
	[ -f "$recipe" ] || continue

	# Is this archive actually consumed? The recipe must NAME it, either as
	# a literal path or through the basename it builds from. A recipe that
	# never mentions the name is not building from it.
	if ! grep -qF "$base" "$recipe" 2>/dev/null; then
		printf 'ORPHAN\t%s\t%s\n' "$pkg" "$rel" >> "$work/report"
		continue
	fi
	consumed=$((consumed + 1))

	sidecar=$archive.sha256
	if [ ! -f "$sidecar" ]; then
		unpinned="$unpinned $rel"
		continue
	fi
	pinned=$((pinned + 1))

	# The sidecar must be sha256sum -c compatible and name the file.
	sidecar_name=$(awk 'NF { print $2; exit }' "$sidecar")
	if [ "$sidecar_name" != "$base" ]; then
		fail "sidecar for $rel names '$sidecar_name', expected '$base'"
	fi
	# And the bytes must actually verify against it. The sidecar existing
	# is not the same as the archive being intact.
	if ! (cd "$(dirname "$archive")" && sha256sum -c "$(basename "$sidecar")" >/dev/null 2>&1); then
		fail "vendored archive does not match its own sidecar: $rel
       The bytes in the tree are not the bytes the recipe pins. Do NOT
       regenerate the sidecar to make this pass: that would pin whatever
       happens to be present, which is inventing a hash from an untrusted
       input. Establish which side is wrong first."
	fi
done < "$work/archives"

ok "$consumed archive(s) are consumed by a recipe"

# The recipe's OWN declared hash must also match the vendored bytes. This
# is a different check from the sidecar: the sidecar can be regenerated by
# accident, but the recipe's hash came from upstream and is the real pin.
declare_mismatch=""
while IFS= read -r archive; do
	rel=${archive#"$root"/}
	pkg=$(printf '%s' "$rel" | cut -d/ -f1)
	base=${archive##*/}
	recipe=$root/$pkg/recipe.sh
	[ -f "$recipe" ] || continue
	grep -qF "$base" "$recipe" 2>/dev/null || continue
	[ -f "$archive.sha256" ] || continue

	actual=$(sha256sum "$archive" | cut -d' ' -f1)
	# Every 64-hex literal in the recipe is a candidate pin (recipes use
	# sha256=, <name>_sha256=, and per-version pairs in a case).
	if ! grep -qE "\b$actual\b" "$recipe"; then
		# Multi-version recipes legitimately declare several hashes, so
		# only report when the recipe declares exactly one.
		count=$(grep -oE '\b[0-9a-f]{64}\b' "$recipe" | sort -u | wc -l)
		[ "$count" -eq 1 ] && declare_mismatch="$declare_mismatch $rel"
	fi
done < "$work/archives"

[ -z "$declare_mismatch" ] ||
	fail "vendored bytes disagree with the recipe's declared upstream hash:$declare_mismatch
       The recipe pins one hash and the vendored bytes are not it. Do NOT
       edit the recipe's hash to match: that removes the pin rather than
       satisfying it. Re-fetch from upstream and compare."
ok "every consumed archive matches the hash its recipe declares"

if [ -n "$unpinned" ]; then
	printf '%s\n' "supply-chain: consumed archive(s) with no sha256 sidecar:" >&2
	for a in $unpinned; do printf '    %s\n' "$a" >&2; done
	printf '%s\n' "supply-chain: run saphira-packager/files/vendor-sidecars to emit them" >&2
	printf '%s\n' "supply-chain: (it verifies bytes against the recipe's upstream hash first)" >&2
	exit 1
fi
ok "every consumed archive carries a sha256 sidecar ($pinned pinned)"

# --- 2. report orphans, never fail on them ---------------------------

orphans=$(grep -c '^ORPHAN' "$work/report" 2>/dev/null || echo 0)
if [ "$orphans" -gt 0 ]; then
	printf '%s\n' "supply-chain: notice: $orphans unreferenced archive(s) in files/ trees."
	printf '%s\n' "supply-chain: notice: these are NOT build input and are deliberately"
	printf '%s\n' "supply-chain: notice: not pinned or failed. They are usually a superseded"
	printf '%s\n' "supply-chain: notice: tarball left beside the current one. Removing them is"
	printf '%s\n' "supply-chain: notice: safe and shrinks the tree; it is an operator decision"
	printf '%s\n' "supply-chain: notice: because a superseded archive is sometimes kept on purpose."
	grep '^ORPHAN' "$work/report" | while IFS="$(printf '\t')" read -r _ pkg rel; do
		printf '    %s\n' "$rel" >&2
	done
fi
ok "unreferenced archives reported, not pinned and not failed ($orphans)"

# --- 3. sidecars must describe a file that EXISTS ----------------------
#
# The checks above all run in one direction: for every archive a recipe
# consumes, is there a correct sidecar? That leaves the inverse completely
# unexamined -- a sidecar naming a file that is not in the tree.
#
# espeak-ng/files/espeak-ng-1.51.tar.gz.sha256 was exactly that: the recipe
# vendors the archive as 1.51.tar.gz (matching the source URL basename),
# so the archive named by the sidecar did not exist, and the hash it
# recorded was not the recipe's declared hash either. It was a claim about
# bytes nobody had, waiting to "verify" a file if one were ever dropped in
# beside it. A sidecar is supposed to be evidence, so a sidecar with
# nothing to describe is a defect, not trivia.
#
# This fails rather than warns: unlike a superseded archive, which is a
# judgement call, a sidecar with no file cannot be legitimate.
find "$root" -path "$root/.git" -prune -o -type f -name '*.sha256' -print |
	sort > "$work/sidecars"
dangling=""
while IFS= read -r sidecar; do
	[ -f "$sidecar" ] || continue
	# The sidecar names its subject on the second field.
	subject=$(awk 'NR == 1 { print $2; exit }' "$sidecar" 2>/dev/null)
	[ -n "$subject" ] || continue
	case $subject in
	/*) continue ;;
	esac
	[ -f "$(dirname "$sidecar")/$subject" ] && continue
	dangling="$dangling ${sidecar#"$root"/}"
done < "$work/sidecars"
if [ -n "$dangling" ]; then
	printf '%s\n' "supply-chain: sidecar(s) naming a file that does not exist:" >&2
	for s in $dangling; do printf '    %s\n' "$s" >&2; done
	printf '%s\n' "supply-chain: each is a claim about bytes that are not here." >&2
	printf '%s\n' "supply-chain: Delete the sidecar, or restore the archive it describes." >&2
	exit 1
fi
ok "every sidecar describes a file that actually exists"

# --- 4. cross-recipe archive references are pinned too ----------------
#
# Everything above attributes an archive to the recipe whose files/ it
# lives in. That breaks the moment a recipe builds from ANOTHER recipe's
# vendored archive, which is legitimate and now real: bpftool has
# no standalone upstream tarball (upstream ships bpftool only inside the
# kernel tree) so it builds from saphira-kernel's already-vendored,
# already-verified linux tarball, version-locked to the kernel it ships
# with.
#
# The risk of the pattern is that the second consumer is invisible to the
# per-package check: bpftool would be consuming an archive that no
# check attributes to it. So the reference is followed explicitly and the
# sidecar beside the referenced archive must exist and verify.
#
# The reference is resolved at DIRECTORY granularity, not by matching the
# whole path. The first attempt matched the path with a character class of
# [A-Za-z0-9._+-] and therefore matched nothing at all for the case it was
# written for: bpftool's archive is named with an interpolated variable
# ($RECIPE_DIR/../saphira-kernel/files/linux-${KVER}.tar.xz), and the
# braces and dollar are outside that class. A check that silently skips
# the reference it was added for is worse than no check, so the directory
# is taken and every archive inside it is required to be pinned.
crossrefs=0
while IFS= read -r recipe; do
	rel=${recipe#"$root"/}
	dir=$(dirname "$recipe")
	# Each referenced files/ directory, however the file inside it is named.
	grep -oE '\.\./[A-Za-z0-9._-]+/files' "$recipe" 2>/dev/null | sort -u |
	while IFS= read -r reldir; do
		target=$dir/$reldir
		[ -d "$target" ] || continue
		find "$target" -maxdepth 1 -type f \
			\( -name '*.tar.gz' -o -name '*.tar.xz' -o -name '*.tar.bz2' \
			-o -name '*.tar.zst' -o -name '*.tar.lz' -o -name '*.tar.lzma' \
			-o -name '*.tgz' -o -name '*.tbz2' -o -name '*.zip' -o -name '*.whl' \) \
			-print | sort | while IFS= read -r subject; do
			printf '%s\t%s\n' "$rel" "$subject"
		done
	done
done < "$work/recipes" | sort -u > "$work/crossrefs"

while IFS="$(printf '\t')" read -r consumer subject; do
	[ -n "$consumer" ] || continue
	[ -f "$subject" ] || continue
	if [ ! -f "$subject.sha256" ]; then
		printf '%s\n' "supply-chain: $consumer consumes $subject," >&2
		printf '%s\n' "supply-chain: which carries no sidecar of its own." >&2
		printf '%s\n' "supply-chain: A cross-recipe archive reference must be pinned where it lives." >&2
		exit 1
	fi
	if ! (cd "$(dirname "$subject")" &&
		sha256sum -c "$(basename "$subject").sha256" >/dev/null 2>&1); then
		printf '%s\n' "supply-chain: $consumer consumes $subject, whose sidecar does not verify." >&2
		exit 1
	fi
	crossrefs=$((crossrefs + 1))
done < "$work/crossrefs"

ok "cross-recipe archive references are pinned and verify ($crossrefs reference(s))"

printf '%s\n' "supply-chain: OK ($checks checks, $consumed consumed, $pinned pinned, $orphans orphan)"
